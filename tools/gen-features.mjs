// Writes every feature page from preview-ui/pages/_features.mjs:
//   preview-ui/pages/feature-<slug>.{jsx,css,data.mjs}  (the page bundle, built by build:preview)
//   features/<slug>.md                                    (Jekyll front matter: URL, description, FAQ schema)
// Run: node tools/gen-features.mjs, then npm run build:preview.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { parse } from 'yaml';
import { FEATURES, fill } from '../preview-ui/pages/_features.mjs';

const pricing = parse(await readFile('_data/pricing.yml', 'utf8'));
const q = (s) => JSON.stringify(s);
await mkdir('features', { recursive: true });

for (const f of FEATURES) {
  const id = `feature-${f.slug}`;
  await writeFile(`preview-ui/pages/${id}.jsx`, `// Generated by tools/gen-features.mjs. Edit preview-ui/pages/_features.mjs instead.\nimport React from 'react';\nimport FeaturePage from './_feature.jsx';\nexport default function Page({ data }) { return <FeaturePage slug=${q(f.slug)} data={data} />; }\n`);
  await writeFile(`preview-ui/pages/${id}.css`, `@import "../../../preview-ui/pages/_feature.css";\n`);
  // Related guides: read each article's title at build time, so a renamed article never shows a stale title.
  await writeFile(`preview-ui/pages/${id}.data.mjs`, `// Generated by tools/gen-features.mjs.\nimport { readFile } from 'node:fs/promises';\nconst SLUGS = ${q(f.articles)};\nexport default async () => ({ articles: (await Promise.all(SLUGS.map(async (s) => {\n  try { const md = await readFile(\`articles/\${s}.md\`, 'utf8'); const t = md.match(/^title:\\s*"?(.*?)"?\\s*$/m); return t ? { href: \`/articles/\${s}/\`, title: t[1].replace(/\\\\"/g, '"') } : null; } catch { return null; }\n}))).filter(Boolean) });\n`);
  const faq = f.faq.map(([qq, a]) => `  - q: ${q(qq)}\n    a: ${q(fill(a, pricing))}`).join('\n');
  await writeFile(`features/${f.slug}.md`, `---\nlayout: react\nreact: ${id}\ntitle: ${q(f.name)}\nparent: Features\npermalink: /features/${f.slug}/\ndescription: ${q(f.description)}\nfaq:\n${faq}\n---\n`);
  console.log(`features/${f.slug}`);
}
